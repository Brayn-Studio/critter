"""Generates the Android app's icons from Sprig's pixels (design §8.1): the adaptive launcher icon's background
(the dawn sky over a strip of grass), its foreground (Sprig's `base` pose) and its monochrome layer (the same
outline with the eyes cut out), and the status bar icon. Every row's run of same-colored cells becomes one
rectangle in its color's path, so the vectors stay crisp at any size. The output depends only on the manifest:
running it again gives the same files. Usage, from the repository root:
  python3 scripts/dev/make-android-icons.py
"""
import json
import os
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
MANIFEST = os.path.join(ROOT, 'Skins', 'sprig', 'manifest.json')
DRAWABLE = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res', 'drawable')

# The adaptive icon: 108dp in 36 x 36 cells of 3dp; the visible part is the middle 72dp, the safe zone 66dp.
CELLS = 36
GROUND = 23  # the grass starts on this row
SPRIG_AT = (9, 13)  # where Sprig's base box (column 0, row 0) goes: centered, its feet on the grass

# The status bar icon: Sprig's outline in 12 x 11 cells of 2dp, white, in a 24dp box (the mockup's SB_ICON).
SB_ICON = ['..###..###..', '...######...', '..########..', '.##########.', '############', '##.######.##',
           '##.######.##', '############', '############', '.##########.', '..########..']

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/dev/make-android-icons.py (Sprig, Skins/sprig/manifest.json); do not edit. -->\n'


def sky_and_grass():
    """The background layer, cell by cell: the dawn sky in three bands with a dithered row at each edge, then the
    grass with its light top row, a few blades poking into the sky and dark specks (the mockup's iconGrid)."""
    cells = {}
    for y in range(CELLS):
        for x in range(CELLS):
            c = '#8FCEFF' if y < 10 else '#B4DEFF' if y < 17 else '#D6EEFF' if y < GROUND else '#8ED07A'
            if y == 10 and x % 2 == 0:
                c = '#8FCEFF'
            if y == 9 and x % 4 == 1:
                c = '#B4DEFF'
            if y == 17 and x % 2 == 0:
                c = '#B4DEFF'
            if y == 16 and x % 4 == 1:
                c = '#D6EEFF'
            if y == GROUND:
                c = '#B5E39C'
            if y == GROUND - 1 and (x % 7 == 2 or x % 11 == 6):
                c = '#B5E39C'
            if y > GROUND + 1 and (x * 7 + y * 13) % 17 == 0:
                c = '#6DB65A'
            cells[(x, y)] = c
    return cells


def base_pose(manifest):
    """Sprig's `base` pose as {(x, y): palette character} in base-box cells, parts laid over each other in order
    (later parts cover earlier ones), like SkinRenderer.grid."""
    pixels = {}
    for name in manifest['poses']['base']:
        part = manifest['parts'][name]
        ax, ay = part['at']
        for r, line in enumerate(part['rows']):
            for c, ch in enumerate(line):
                if ch != '.':
                    pixels[(ax + c, ay + r)] = ch
    return pixels


def runs(cells, width, height):
    """{color: [(x, y, w)]}: each row's runs of one color, top to bottom, left to right; colors in order of first
    appearance."""
    out = {}
    for y in range(height):
        x = 0
        while x < width:
            c = cells.get((x, y))
            if c is None:
                x += 1
                continue
            end = x
            while end + 1 < width and cells.get((end + 1, y)) == c:
                end += 1
            out.setdefault(c, []).append((x, y, end - x + 1))
            x = end + 1
    return out


def vector(cells, width, height, size_dp, scale=1, dy=0, viewport=None):
    """A vector drawable of `cells` ({(x, y): color}), `scale` viewport units a cell, shifted down by `dy` units."""
    vw, vh = viewport or (width * scale, height * scale)
    lines = ['<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             f'    android:width="{size_dp}dp"',
             f'    android:height="{size_dp}dp"',
             f'    android:viewportWidth="{vw}"',
             f'    android:viewportHeight="{vh}">']
    for color, rects in runs(cells, width, height).items():
        data = ''.join(f'M{x * scale},{y * scale + dy}h{w * scale}v{scale}h-{w * scale}z' for x, y, w in rects)
        lines.append(f'    <path android:fillColor="{color}" android:pathData="{data}" />')
    lines.append('</vector>')
    return HEADER + '\n'.join(lines) + '\n'


def write(name, text):
    path = os.path.join(DRAWABLE, name)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.relpath(path, ROOT))


def main():
    with open(MANIFEST, encoding='utf-8') as f:
        manifest = json.load(f)
    palette = manifest['palette']
    sprig = {(x + SPRIG_AT[0], y + SPRIG_AT[1]): ch for (x, y), ch in base_pose(manifest).items()}
    for (x, y) in sprig:
        assert 0 <= x < CELLS and 0 <= y < CELLS, f'Sprig does not fit the icon at {(x, y)}'

    os.makedirs(DRAWABLE, exist_ok=True)
    write('ic_launcher_background.xml', vector(sky_and_grass(), CELLS, CELLS, 108))
    write('ic_launcher_foreground.xml', vector({k: palette[ch].upper() for k, ch in sprig.items()}, CELLS, CELLS, 108))
    # The system tints the monochrome layer itself; the eyes (o) and their shine (w) are cut out.
    mono = {k: '#FFFFFF' for k, ch in sprig.items() if ch not in ('o', 'w')}
    write('ic_launcher_monochrome.xml', vector(mono, CELLS, CELLS, 108))
    bar = {(x, y): '#FFFFFF' for y, row in enumerate(SB_ICON) for x, ch in enumerate(row) if ch == '#'}
    # 12 x 11 cells of 2 units in a 24 x 24 box: one unit of room above and below.
    write('ic_stat_critter.xml', vector(bar, 12, 11, 24, scale=2, dy=1, viewport=(24, 24)))


if __name__ == '__main__':
    main()
