    /** Each row's horizontal runs of `#` as `[x, y, length]`, so an icon is drawn with a few rectangles. */
    fun runs(rows: List<String>): List<IntArray> {
        val out = ArrayList<IntArray>()
        for ((y, row) in rows.withIndex()) {
            var x = 0
            while (x < row.length) {
                if (row[x] != '#') {
                    x++
                    continue
                }
                var end = x
                while (end < row.length && row[end] == '#') end++
                out += intArrayOf(x, y, end - x)
                x = end
            }
        }
        return out
    }
